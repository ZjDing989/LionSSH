/** Translate UI messages only. User names, paths and terminal output are never translation keys. */
export function t(source: string, vars?: Record<string, string | number | null | undefined>): string {
  const text = language.value.resolved === 'en' ? translations[source] ?? source : source;
  return vars ? text.replace(/\{([^{}]+)\}/g, (match, key: string) => Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key] ?? '') : match) : text;
}

const terminalErrorPatterns = [
  [/^复制失败：([\s\S]*)$/, '复制失败：{error}'],
  [/^粘贴失败：([\s\S]*)$/, '粘贴失败：{error}'],
] as const;
export function message(source?: string | null): string {
  if (!source) return '';
  for (const [pattern, key] of terminalErrorPatterns) {
    const match = source.match(pattern);
    if (match) return t(key, { error: backendMessage(match[1], language.value.resolved) });
  }
  return t(backendMessage(source, language.value.resolved));
}

