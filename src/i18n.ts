/** A Chinese system locale uses Chinese; every other locale falls back to English. */
export function resolveLanguage(preference: LanguagePreference, locale = typeof navigator === 'undefined' ? 'en' : navigator.language): 'zh' | 'en' {
  return preference === 'zh' || preference === 'en' ? preference : /^zh(?:[-_]|$)/i.test(locale) ? 'zh' : 'en';
}
function cachedPreference(): LanguagePreference {
  try {
    const saved = localStorage.getItem('lion-language');
    return saved === 'zh' || saved === 'en' ? saved : 'system';
  } catch { return 'system'; }
}
const preference = cachedPreference();
export const language = ref<LanguageState>({ preference, resolved: resolveLanguage(preference) });
export function applyLanguage(state: LanguageState) {
  language.value = { ...state };
  if (typeof document !== 'undefined') {
    document.documentElement.lang = state.resolved === 'zh' ? 'zh-CN' : 'en';
    document.title = 'Lion SSH';
    const shellCaption = document.querySelector('#startup-shell > span');
    if (shellCaption) shellCaption.textContent = t('正在打开工作台');
  }
  try { localStorage.setItem('lion-language', state.preference); } catch { /* Language remains usable without browser storage. */ }
}

